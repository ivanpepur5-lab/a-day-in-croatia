// Dumps every line of Croatia Adventure story text into docs/ADVENTURE_SCRIPT.md,
// so a local reviewer can read (and mark up) the whole script on a phone.
//   node scripts/adventure-script.mjs
import { writeFileSync } from 'node:fs';
import { EVENTS, BASES, TRAVEL, DAY4, DAY5, ACTIVITIES, ENDINGS, ARRIVAL, NARRATOR, DESTINATIONS } from '../src/adventure/data/story.js';
import { newGame } from '../src/adventure/engine/game.js';

// a few contrasting states so state-dependent text shows its variants
const base = newGame({ seed: 'script' });
const SAMPLES = [
  { ...base, day: 3, location: 'split', base: 'apartment', route: ['split', 'trogir', 'split'], visited: ['split', 'trogir'], flags: { marija: true, bigFish: true, bigFishPlace: 'split', dujePlan: 'coffee', ante: 1, shirt: 1, goatExcuse: true, bocceWin: true, posuda: 1, pekaPlace: 'split', grandpa: true, lukaManager: true, hamCarry: true, oliveOil: true } },
  { ...base, day: 4, location: 'hvar', base: 'hostel', route: ['split', 'omis', 'hvar', 'hvar'], visited: ['split', 'omis', 'hvar'], flags: { hostel: true, stranded: true, dujePlan: 'picigin', referee: true, lukaGuitar: true, benchNights: 1, pekaPlace: 'trogir', car: true, shirtHelped: 1, magnets: 1 } },
  { ...base, day: 5, location: 'brac', base: 'boutique', route: ['split', 'krka', 'brac', 'brac', 'brac'], visited: ['split', 'krka', 'brac'], money: 40, flags: { boutique: true, dujePlan: 'song', sunburn: true, anteDolphin: true } },
];
const all = (v) => {
  if (v === undefined || v === null) return [];
  if (typeof v !== 'function') return [v];
  return [...new Set(SAMPLES.map((s) => { try { return v(s); } catch { return null; } }).filter(Boolean))];
};
const q = (v) => all(v).map((t) => `> ${t}`).join('\n>\n');
let md = `# Croatia Adventure — full script\n\nGenerated by \`node scripts/adventure-script.mjs\`. Every line of story text in the game, for review by a local Croatian reader. Lines marked 💬 are Duje, the narrator. Where text changes with the player's history, each variant is shown.\n\nPlease mark anything that is **wrong, unnatural, offensive or not funny to a local** — and suggest a better line if you have one. The checklist of cultural references is in \`docs/LOCAL_REVIEW.md\`.\n\n## Narrator\n\n${q(NARRATOR.intro)}\n`;
const choice = (c) => {
  let out = `- **${all(c.label).join(' / ')}**${c.hint ? ` — _${c.hint}_` : ''}\n`;
  const branches = c.chance ? [['🎲 lucky', c.chance.success], ['🎲 unlucky', c.chance.fail]] : [['', c]];
  for (const [tag, b] of branches) for (const t of all(b.result)) out += `  - ${tag ? `${tag}: ` : ''}${t}\n`;
  for (const t of all(c.duje)) out += `  - 💬 ${t}\n`;
  return out;
};
md += `\n## Bases\n\n${BASES.map(choice).join('')}`;
md += `\n## Travel\n\n`;
for (const d of [1, 2, 3, 4, 5]) {
  md += `### ${TRAVEL[d].title}\n\n💬\n${q(TRAVEL[d].prompt)}\n\n${TRAVEL[d].choices.map(choice).join('')}\n`;
}
md += `### Day 4 and day 5 options\n\n${[...Object.values(DAY4), ...Object.values(DAY5)].map(choice).join('')}\n`;
md += `\n## Arrivals and activities\n\n`;
for (const [id, list] of Object.entries(ACTIVITIES)) {
  md += `### ${DESTINATIONS[id].name}\n\n💬 First visit:\n${q(ARRIVAL[id].first)}\n\n💬 Return visit:\n${q(ARRIVAL[id].again)}\n\n${list.map(choice).join('')}\n`;
}
md += `\n## Events (${EVENTS.length})\n\n`;
for (const e of EVENTS) {
  const tags = [e.kind === 'callback' ? '↩ consequence' : e.kind === 'hidden' ? '🔎 hidden' : null, e.slot, `where: ${e.where.join(', ')}`].filter(Boolean).join(' · ');
  md += `### ${all(e.title).join(' / ')} \`${e.id}\`\n\n_${tags}_${e.hint ? `\n\n_Hint: ${e.hint}_` : ''}\n\n${q(e.story)}\n\n${e.choices.map(choice).join('')}${e.broke ? `- _When broke:_ ${e.broke.result}\n  - 💬 ${e.broke.duje}\n` : ''}\n`;
}
md += `\n## Endings\n\n${ENDINGS.map((e) => `### ${e.emoji} ${e.title}\n\n💬 “${e.verdict}”\n\n${e.epilogue}\n`).join('\n')}`;
writeFileSync('docs/ADVENTURE_SCRIPT.md', md);
console.log(`Wrote docs/ADVENTURE_SCRIPT.md (${md.split('\n').length} lines, ${EVENTS.length} events)`);
