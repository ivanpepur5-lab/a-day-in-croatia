/**
 * Travel-data audit.
 *
 *   npm run audit                 report + regenerate docs/UNVERIFIED.md and docs/VERIFIED_SOURCES.md
 *   npm run audit:check           same, but exit 1 if there are errors (use in CI / before deploys)
 *   npm run audit -- --strict     also exit 1 on warnings (stale or expired verifications)
 *   npm run audit -- --today=2027-03-01   audit as of another date
 *
 * Rules live in src/data/audit.js; the data in src/data/travel-data.json.
 */
import { writeFileSync } from 'node:fs';
import TRAVEL from '../src/data/travel-data.json' with { type: 'json' };
import { auditTravelData } from '../src/data/audit.js';
import { displayState, formatCheckDate } from '../src/data/verification.js';
import { LOCATIONS } from '../src/data/locations.js';
import { PROMET_FARES, FARE_SOURCE, MUNICIPALITY } from '../src/data/fares.js';
import { dateKey } from '../src/engine/daily.js';
import { TIPS, TIP_CATEGORIES } from '../src/adventure/data/tips.js';

const arg = (name) => process.argv.find((a) => a.startsWith(`--${name}`));
const today = arg('today')?.split('=')[1] ?? dateKey(new Date());
const check = Boolean(arg('check'));
const strict = Boolean(arg('strict'));
const root = new URL('../docs/', import.meta.url).pathname;
const esc = (t) => String(t ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const link = (s) => `[${esc(s.label)}](${s.url})`;
const opts = { today, defaultReviewDays: TRAVEL.meta.defaultReviewDays };

// ---------------------------------------------------------------- audit
const result = auditTravelData(TRAVEL, { today, locationIds: LOCATIONS.map((l) => l.id) });
const C = { red: '\x1b[31m', yellow: '\x1b[33m', green: '\x1b[32m', dim: '\x1b[2m', off: '\x1b[0m' };
console.log(`Travel data audit as of ${today}\n`);
for (const i of result.issues) {
  const col = i.level === 'error' ? C.red : C.yellow;
  console.log(`${col}${i.level.toUpperCase().padEnd(7)}${C.off} ${i.code.padEnd(20)} ${i.where}\n        ${C.dim}${i.message}${C.off}`);
}

// ---------------------------------------------------------------- Croatia Adventure tips
const tipIssues = [];
for (const t of TIPS) {
  const v = t.verification;
  if (v.status === 'verified') {
    for (const id of [v.source, ...(v.alsoSources ?? [])]) {
      if (!TRAVEL.sources[id]) tipIssues.push({ level: 'error', code: 'TIP_SOURCE_UNKNOWN', where: `adventure tip ${t.id}`, message: `Unknown source "${id}".` });
    }
    const st = displayState({ status: 'verified', verifiedOn: v.verifiedOn, validUntil: v.validUntil }, opts);
    if (st.state === 'stale') tipIssues.push({ level: 'warning', code: 'TIP_STALE', where: `adventure tip ${t.id}`, message: `Verified ${v.verifiedOn}: ${st.reason}.` });
  } else if (v.status !== 'editorial') {
    tipIssues.push({ level: 'error', code: 'TIP_STATUS', where: `adventure tip ${t.id}`, message: 'Tip status must be "verified" or "editorial".' });
  }
}
for (const i of tipIssues) {
  result.issues.push(i);
  (i.level === 'error' ? result.errors : result.warnings).push(i);
  const col = i.level === 'error' ? C.red : C.yellow;
  console.log(`${col}${i.level.toUpperCase().padEnd(7)}${C.off} ${i.code.padEnd(20)} ${i.where}\n        ${C.dim}${i.message}${C.off}`);
}

// ---------------------------------------------------------------- collect
const rows = { verified: [], stale: [], unverified: [], estimate: [] };
for (const l of LOCATIONS) {
  const items = [
    { ...l.price, field: 'Price per person (used in game)', value: `€${l.costPerPerson}${l.costNote ? ` — ${l.costNote}` : ''}` },
    { ...l.visit, field: 'Time on site (used in game)', value: `${l.visit.value} min`, note: l.visit.note },
    ...l.facts,
  ];
  for (const f of items) {
    const st = displayState(f, opts);
    rows[st.state].push({ loc: l.name, f, st });
  }
}
const fareState = displayState({ status: 'verified', ...FARE_SOURCE }, opts);

// ---------------------------------------------------------------- UNVERIFIED.md
let u = `# Information that still needs manual verification\n\nGenerated by \`npm run audit\` from \`src/data/travel-data.json\` on ${today}. Edit the data file, then re-run the audit. See [EDITING_DATA.md](EDITING_DATA.md).\n\n`;
u += `## Unverified real-world claims (${rows.unverified.length})\n\nThese are shown as **Unverified** in the app.\n\n| Location | Item | Shown as | Where to verify | Note |\n|---|---|---|---|---|\n`;
for (const { loc, f } of rows.unverified) u += `| ${loc} | ${esc(f.field)} | ${esc(f.value)} | ${(f.toVerify ?? []).map(link).join('<br>')} | ${esc(f.note)} |\n`;

u += `\n## Verified, but due for a re-check (${rows.stale.length + (fareState.state === 'stale' ? 1 : 0)})\n\n`;
if (rows.stale.length === 0 && fareState.state !== 'stale') u += `None as of ${today}.\n`;
else {
  u += `| Location | Item | Last checked | Why | Source |\n|---|---|---|---|---|\n`;
  for (const { loc, f, st } of rows.stale) u += `| ${loc} | ${esc(f.field)} | ${f.verifiedOn} | ${esc(st.reason)} | ${f.source ? link(f.source) : ''} |\n`;
  if (fareState.state === 'stale') u += `| All | Bus fares | ${FARE_SOURCE.verifiedOn} | ${esc(fareState.reason)} | ${link(FARE_SOURCE)} |\n`;
}

u += `\n## Game estimates (${rows.estimate.length})\n\nThese are game values. The app always shows them with “≈” / “est.”, never as official prices.\n\n| Location | Item | Value | Where an official value could be checked |\n|---|---|---|---|\n`;
for (const { loc, f } of rows.estimate) u += `| ${loc} | ${esc(f.field)} | ${esc(f.value)} | ${(f.toVerify ?? []).map(link).join('<br>') || '—'} |\n`;

const places = Object.keys(MUNICIPALITY);
const missing = new Set();
for (const a of places) for (const b of places) {
  const ma = MUNICIPALITY[a];
  const mb = MUNICIPALITY[b];
  if (a >= b || (ma && ma === mb)) continue;
  const names = [ma ?? 'Krka (Skradin)', mb ?? 'Krka (Skradin)'].sort();
  if (!ma || !mb || !PROMET_FARES[[ma, mb].sort().join('|')]) missing.add(names.join(' – '));
}
u += `\n### Bus journeys without an official fare (estimated in game)\n\n${[...missing].sort().map((m) => `- ${m}`).join('\n')}\n`;
u += `\n### Always estimated\n\n- **Travel times** for every leg (distance model in \`src/engine/travel.js\`, not timetables).\n- **Time on site** for every location.\n`;
const editorial = TIPS.filter((t) => t.verification.status === 'editorial');
u += `\n## Croatia Adventure — editorial tips for periodic review (${editorial.length})\n\nThese tips are general knowledge (culture, language, food, practical habits). They contain no prices, times or schedules (a test enforces this), but a human should re-read them from time to time. Tips with prices or rules use verified sources instead.\n\n| Tip | Category | Text |\n|---|---|---|\n`;
for (const t of editorial) u += `| ${esc(t.title)} | ${TIP_CATEGORIES[t.category].label} | ${esc(t.tip)} |\n`;
writeFileSync(`${root}UNVERIFIED.md`, u);

// ---------------------------------------------------------------- VERIFIED_SOURCES.md
let v = `# Verified facts and sources\n\nGenerated by \`npm run audit\` on ${today}. Review window: ${TRAVEL.meta.defaultReviewDays} days unless an item sets \`reviewDays\`.\n\n| Location | Item | Value | Source | Last verified | Valid |\n|---|---|---|---|---|---|\n`;
for (const { loc, f } of [...rows.verified, ...rows.stale]) {
  const valid = [f.validFrom && `from ${f.validFrom}`, f.validUntil && `until ${f.validUntil}`].filter(Boolean).join(' ');
  v += `| ${loc} | ${esc(f.field)} | ${esc(f.value)} | ${link(f.source)} | ${formatCheckDate(f.verifiedOn)} | ${valid} |\n`;
}
v += `\n## Official Promet Split fares (per person)\n\nSource: ${link(FARE_SOURCE)}, last verified ${formatCheckDate(FARE_SOURCE.verifiedOn)}, valid from ${FARE_SOURCE.validFrom}. The game charges the online / ticket-office fare × party size.\n\n| Journey | Online / ticket office | From the driver | Valid (min) | 2 people, online | 2 people, driver |\n|---|---|---|---|---|---|\n`;
for (const [k, f] of Object.entries(PROMET_FARES)) {
  v += `| ${k.replace('|', ' – ')} | €${f.online.toFixed(2)} | €${f.driver.toFixed(2)} | ${f.validityMin} | €${(f.online * 2).toFixed(2)} | €${(f.driver * 2).toFixed(2)} |\n`;
}
writeFileSync(`${root}VERIFIED_SOURCES.md`, v);

// ---------------------------------------------------------------- summary
console.log(
  `\n${C.green}${rows.verified.length} verified${C.off} · ${C.yellow}${rows.stale.length} need re-check${C.off} · ` +
    `${rows.unverified.length} unverified · ${rows.estimate.length} estimates · ${Object.keys(PROMET_FARES).length} official fares`,
);
console.log(`${result.errors.length} error(s), ${result.warnings.length} warning(s). Wrote docs/UNVERIFIED.md and docs/VERIFIED_SOURCES.md`);
if ((check || strict) && result.errors.length) process.exit(1);
if (strict && result.warnings.length) process.exit(1);
