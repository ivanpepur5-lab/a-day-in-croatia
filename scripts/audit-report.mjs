// Generates docs/UNVERIFIED.md and docs/VERIFIED_SOURCES.md straight from the data,
// so the lists can never drift from what the app shows.   npm run audit
import { writeFileSync } from 'node:fs';
import { LOCATIONS, AUDIT_DATE } from '../src/data/locations.js';
import { PROMET_FARES, FARE_SOURCE, MUNICIPALITY } from '../src/data/fares.js';

const root = new URL('../docs/', import.meta.url).pathname;
const esc = (t) => String(t).replace(/\|/g, '\\|');

// ---- unverified + estimates
let u = `# Remaining unverified information\n\nGenerated from \`src/data/locations.js\` and \`src/data/fares.js\` by \`npm run audit\` (audit date ${AUDIT_DATE}).\n\n`;
u += `## Unverified real-world claims\n\nThese are labelled **Unverified** in the app. Each lists where to check it.\n\n| Location | Field | Shown as | Where to verify | Note |\n|---|---|---|---|---|\n`;
let nUnv = 0;
for (const l of LOCATIONS) {
  for (const f of l.facts.filter((x) => x.status === 'unverified')) {
    nUnv++;
    u += `| ${l.name} | ${esc(f.field)} | ${esc(f.value)} | ${f.toVerify.map((s) => `[${esc(s.label)}](${s.url})`).join('<br>')} | ${esc(f.note ?? '')} |\n`;
  }
}
u += `\n## Game estimates (not real-world claims)\n\n| Location | Field | Value | Note |\n|---|---|---|---|\n`;
for (const l of LOCATIONS) {
  for (const f of l.facts.filter((x) => x.status === 'estimate')) {
    u += `| ${l.name} | ${esc(f.field)} | ${esc(f.value)} | ${esc(f.note ?? '')} |\n`;
  }
  if (l.costStatus !== 'verified' && !l.facts.some((f) => f.status === 'estimate' && /€/.test(f.value))) {
    u += `| ${l.name} | Cost used in game | €${l.costPerPerson} per person | ${esc(l.costNote)} |\n`;
  }
}
// fares not covered
const places = Object.keys(MUNICIPALITY);
const missing = new Set();
for (const a of places) for (const b of places) {
  const ma = MUNICIPALITY[a], mb = MUNICIPALITY[b];
  if (a >= b || ma === mb && ma) continue;
  const key = [ma, mb].sort().join('|');
  if (!ma || !mb) missing.add([ma ?? 'Krka (Skradin)', mb ?? 'Krka (Skradin)'].sort().join(' – '));
  else if (!PROMET_FARES[key]) missing.add(`${ma} – ${mb}`);
}
u += `\n### Bus journeys without an official fare (estimated in game)\n\n${[...missing].sort().map((m) => `- ${m}`).join('\n')}\n`;
u += `\n### Always estimated\n\n- **Travel times** for every leg come from the distance model in \`src/engine/travel.js\`, not from timetables.\n- **Time on site** for every location.\n`;
u += `\n---\n**${nUnv} unverified facts** remain.\n`;
writeFileSync(`${root}UNVERIFIED.md`, u);

// ---- verified sources
let v = `# Verified facts and sources\n\nGenerated by \`npm run audit\`.\n\n| Location | Field | Value | Source | Checked |\n|---|---|---|---|---|\n`;
let nVer = 0;
for (const l of LOCATIONS) for (const f of l.facts.filter((x) => x.status === 'verified')) {
  nVer++;
  v += `| ${l.name} | ${esc(f.field)} | ${esc(f.value)} | [${esc(f.source.label)}](${f.source.url}) | ${f.verifiedOn} |\n`;
}
v += `\n## Official Promet Split fares used in the game (per person)\n\nSource: [${FARE_SOURCE.label}](${FARE_SOURCE.url}), checked ${FARE_SOURCE.verifiedOn}. The game charges the online / ticket-office fare × party size.\n\n| Journey | Online / ticket office | From the driver | Valid (min) | For 2 people (online) |\n|---|---|---|---|---|\n`;
for (const [k, f] of Object.entries(PROMET_FARES)) {
  v += `| ${k.replace('|', ' – ')} | €${f.online.toFixed(2)} | €${f.driver.toFixed(2)} | ${f.validityMin} | €${(f.online * 2).toFixed(2)} |\n`;
}
writeFileSync(`${root}VERIFIED_SOURCES.md`, v);
console.log(`${nVer} verified facts, ${nUnv} unverified facts → docs/VERIFIED_SOURCES.md, docs/UNVERIFIED.md`);
